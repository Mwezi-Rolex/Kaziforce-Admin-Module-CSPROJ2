#!/usr/bin/env bash
# ============================================================================
# Kaziforce: one-pass install on a fresh Ubuntu 24.04 Azure VM
# ============================================================================
#
# Automates docs/DEPLOY.md steps 1-9 (packages, service user, firewall,
# PostgreSQL roles, code, backend build, model training, environment file,
# migrations + seed + grants, systemd, Nginx). HTTPS (step 10) and the smoke
# test (step 11) stay separate, manual steps.
#
# Usage, on the VM, from the root of the unpacked bundle:
#   sudo DOMAIN=<vm-dns-name> bash deploy/azure-vm-install.sh 2>&1 | tee ~/install.log
#
# Secrets
#   * Database passwords, the JWT secret and the three operator passwords are
#     generated ON THE VM with openssl and never leave it.
#   * They are written only to /etc/kaziforce/api.env (root:kaziforce 0640) and
#     /root/kaziforce-operator-passwords.txt (root 0600). Nothing is echoed.
#
# Re-running is safe: an existing /etc/kaziforce/api.env is reused (no
# password rotation), the seed runs only once, and models are trained only if
# missing.

set -euo pipefail

DOMAIN="${DOMAIN:?Set DOMAIN to the VM DNS name, e.g. DOMAIN=myvm.region.cloudapp.azure.com}"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP=/opt/kaziforce
WEB=/var/www/kaziforce
ETC=/etc/kaziforce
ENVF="$ETC/api.env"
PASSF=/root/kaziforce-operator-passwords.txt
SEEDED="$ETC/.seeded"

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf '\033[31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" = 0 ] || die "run with sudo"
[ -f "$SRC/server/package.json" ] || die "server/package.json not found under $SRC (unpack the source bundle first)"
[ -f "$SRC/dist/index.html" ] || die "dist/index.html not found under $SRC (unpack the frontend bundle into $SRC/dist)"

# ---------------------------------------------------------------------------
step "1/11 System packages, Node.js 22, pnpm, automatic security updates, fail2ban"
# ---------------------------------------------------------------------------
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y curl ca-certificates gnupg git nginx postgresql postgresql-contrib \
  ufw python3 python3-venv python3-pip rsync openssl \
  unattended-upgrades fail2ban
# Automatic security updates; fail2ban's default jail covers sshd
# (docs/OPERATIONS.md §Security).
systemctl enable --now unattended-upgrades
systemctl enable --now fail2ban
if ! command -v node >/dev/null 2>&1 || ! node --version | grep -q '^v22\.'; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi
npm install -g pnpm@10.34.3
printf 'node %s | pnpm %s | %s | %s\n' "$(node --version)" "$(pnpm --version)" "$(psql --version)" "$(python3 --version)"

# A 4 GiB VM has no swap by default; model training and pnpm install can spike.
if ! swapon --show | grep -q '^/swapfile'; then
  fallocate -l 2G /swapfile
  chmod 600 /swapfile
  mkswap /swapfile >/dev/null
  swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  echo "added 2 GiB swap at /swapfile"
fi

# ---------------------------------------------------------------------------
step "2/11 Service user and directories"
# ---------------------------------------------------------------------------
id kaziforce >/dev/null 2>&1 || useradd --system --create-home --home-dir "$APP" --shell /usr/sbin/nologin kaziforce
mkdir -p "$APP" "$WEB"
install -d -o root -g kaziforce -m 0750 "$ETC"

# ---------------------------------------------------------------------------
step "3/11 Host firewall (ufw): SSH + HTTP + HTTPS only"
# ---------------------------------------------------------------------------
ufw allow OpenSSH >/dev/null
ufw allow 'Nginx Full' >/dev/null
ufw --force enable >/dev/null
ufw status | sed -n '1,12p'

# ---------------------------------------------------------------------------
step "4/11 Secrets (generated here, never printed)"
# ---------------------------------------------------------------------------
if [ -f "$ENVF" ]; then
  echo "reusing existing $ENVF"
  OWNER_PW="$(sed -n 's#^OWNER_DATABASE_URL=postgresql://kaziforce_owner:\([^@]*\)@.*#\1#p' "$ENVF")"
  APP_PW="$(sed -n 's#^DATABASE_URL=postgresql://kaziforce_app:\([^@]*\)@.*#\1#p' "$ENVF")"
  [ -n "$OWNER_PW" ] && [ -n "$APP_PW" ] || die "could not read the database passwords from $ENVF"
else
  OWNER_PW="$(openssl rand -hex 24)"
  APP_PW="$(openssl rand -hex 24)"
  JWT="$(openssl rand -base64 48 | tr -d '\n')"
  SEED_V="$(openssl rand -hex 12)"
  SEED_M="$(openssl rand -hex 12)"
  SEED_S="$(openssl rand -hex 12)"
  umask 027
  cat > "$ENVF" <<EOF
# Generated by deploy/azure-vm-install.sh on $(date -u +%FT%TZ). Never commit or paste.
NODE_ENV=production
PORT=3000
TRUST_PROXY=1
DATABASE_URL=postgresql://kaziforce_app:${APP_PW}@127.0.0.1:5432/kaziforce
OWNER_DATABASE_URL=postgresql://kaziforce_owner:${OWNER_PW}@127.0.0.1:5432/kaziforce
JWT_SECRET=${JWT}
JWT_TTL_HOURS=8
RATE_LIMIT_MAX=600
RATE_LIMIT_WINDOW_MS=300000
MODEL_SERVICE_URL=http://127.0.0.1:8000
MODEL_TIMEOUT_MS=3000
SEED_VIEWER_PASSWORD=${SEED_V}
SEED_MODERATOR_PASSWORD=${SEED_M}
SEED_SUPERADMIN_PASSWORD=${SEED_S}
EOF
  chown root:kaziforce "$ENVF"
  chmod 0640 "$ENVF"
  umask 077
  cat > "$PASSF" <<EOF
# Kaziforce operator sign-in for https://${DOMAIN}  (root-only file; do not paste anywhere)
VIEWER_EMAIL=viewer@kaziforce.local
VIEWER_PASSWORD=${SEED_V}
MODERATOR_EMAIL=moderator@kaziforce.local
MODERATOR_PASSWORD=${SEED_M}
SUPERADMIN_EMAIL=superadmin@kaziforce.local
SUPERADMIN_PASSWORD=${SEED_S}
EOF
  chmod 0600 "$PASSF"
  umask 022
  echo "wrote $ENVF (0640) and $PASSF (0600)"
fi

# ---------------------------------------------------------------------------
step "5/11 PostgreSQL: database and the two roles"
# ---------------------------------------------------------------------------
systemctl enable --now postgresql
sed -e "s/CHANGE_ME_OWNER_PASSWORD/${OWNER_PW}/g" -e "s/CHANGE_ME_APP_PASSWORD/${APP_PW}/g" \
  "$SRC/deploy/sql/01_roles_database.sql" | sudo -u postgres psql -v ON_ERROR_STOP=1 -q
# Backup target (the nightly pg_dump timer writes here; see docs/OPERATIONS.md).
install -d -o postgres -g postgres -m 0750 /var/backups/kaziforce

# ---------------------------------------------------------------------------
step "6/11 Application code and built frontend"
# ---------------------------------------------------------------------------
rsync -a --delete \
  --exclude 'node_modules' --exclude 'dist' --exclude 'ml/.venv' --exclude 'ml/models' \
  --exclude '.local' --exclude '.cache' --exclude '.npm' --exclude '.config' \
  "$SRC/" "$APP/"
chown -R kaziforce:kaziforce "$APP"
rsync -a --delete "$SRC/dist/" "$WEB/"
chown -R root:root "$WEB"
chmod -R a+rX "$WEB"
chmod +x "$APP/deploy/smoke-test.sh"

# ---------------------------------------------------------------------------
step "7/11 Backend: install and compile"
# ---------------------------------------------------------------------------
cd "$APP/server"
sudo -u kaziforce -H pnpm install --frozen-lockfile
sudo -u kaziforce -H pnpm run build
[ -f "$APP/server/dist/index.js" ] || die "server build did not produce dist/index.js"

# ---------------------------------------------------------------------------
step "8/11 Model service: virtualenv and training (synthetic data, fixed seed)"
# ---------------------------------------------------------------------------
cd "$APP/ml"
[ -x .venv/bin/python ] || sudo -u kaziforce -H python3 -m venv .venv
sudo -u kaziforce -H .venv/bin/pip install --quiet --upgrade pip
sudo -u kaziforce -H .venv/bin/pip install --quiet -r requirements.txt
if [ ! -f models/models.joblib ]; then
  for s in generate_data.py train.py anomaly.py evaluate.py; do
    echo "running $s"
    sudo -u kaziforce -H .venv/bin/python "$s"
  done
else
  echo "models/models.joblib present; training skipped"
fi

# ---------------------------------------------------------------------------
step "9/11 Migrations, seed (once) and audit-log grants"
# ---------------------------------------------------------------------------
sudo -u kaziforce -H bash -c "set -a; . '$ENVF'; set +a; cd '$APP/server' && pnpm run migrate"
if [ ! -f "$SEEDED" ]; then
  sudo -u kaziforce -H bash -c "set -a; . '$ENVF'; set +a; cd '$APP/server' && pnpm run seed"
  touch "$SEEDED"
else
  echo "seed already applied ($SEEDED exists); skipped"
fi
OWNER_URL="$(grep '^OWNER_DATABASE_URL=' "$ENVF" | cut -d= -f2-)"
psql "$OWNER_URL" -v ON_ERROR_STOP=1 < "$APP/deploy/sql/02_grants.sql"

# ---------------------------------------------------------------------------
step "10/11 systemd services"
# ---------------------------------------------------------------------------
cp "$APP/deploy/systemd/kaziforce-api.service" /etc/systemd/system/
cp "$APP/deploy/systemd/kaziforce-model.service" /etc/systemd/system/
cp "$APP/deploy/systemd/kaziforce-backup.service" /etc/systemd/system/
cp "$APP/deploy/systemd/kaziforce-backup.timer" /etc/systemd/system/
# journald retention: cap the journal at 200 MB / 30 days (docs/OPERATIONS.md).
mkdir -p /etc/systemd/journald.conf.d
cp "$APP/deploy/systemd/journald-retention.conf" /etc/systemd/journald.conf.d/kaziforce.conf
systemctl restart systemd-journald
systemctl daemon-reload
systemctl enable kaziforce-model kaziforce-api kaziforce-backup.timer >/dev/null
systemctl restart kaziforce-model
systemctl restart kaziforce-api
systemctl enable --now kaziforce-backup.timer

# ---------------------------------------------------------------------------
step "11/11 Nginx site for ${DOMAIN}"
# ---------------------------------------------------------------------------
if [ -f /etc/nginx/sites-available/kaziforce ] && grep -q 'managed by Certbot' /etc/nginx/sites-available/kaziforce; then
  echo "site already carries certbot's HTTPS blocks; left unchanged"
  echo "NOTE: re-apply the security-header include and limit_req edits by hand (docs/OPERATIONS.md §Abuse)."
else
  sed "s/server_name _;/server_name ${DOMAIN};/" "$APP/deploy/nginx/kaziforce.conf" > /etc/nginx/sites-available/kaziforce
fi
cp "$APP/deploy/nginx/kaziforce-headers.conf" /etc/nginx/kaziforce-headers.conf
ln -sf /etc/nginx/sites-available/kaziforce /etc/nginx/sites-enabled/kaziforce
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl reload nginx

# ---------------------------------------------------------------------------
step "Checks"
# ---------------------------------------------------------------------------
check() {
  local label="$1" url="$2" host="${3:-}" i out
  for i in $(seq 1 30); do
    if out="$(curl -fsS --max-time 5 ${host:+-H "Host: $host"} "$url" 2>/dev/null)"; then
      printf '  OK   %-32s %s\n' "$label" "$(printf '%s' "$out" | head -c 160)"
      return 0
    fi
    sleep 2
  done
  printf '  FAIL %-32s %s (see: journalctl -u kaziforce-api -n 50 --no-pager)\n' "$label" "$url"
  return 1
}
RC=0
check "API on loopback"        http://127.0.0.1:3000/api/v1/health || RC=1
check "model service loopback" http://127.0.0.1:8000/health || RC=1
check "API through Nginx"      http://127.0.0.1/api/v1/health "$DOMAIN" || RC=1
check "SPA through Nginx"      http://127.0.0.1/ "$DOMAIN" >/dev/null && echo "  OK   SPA index served" || RC=1

cat <<EOF

Install finished (exit $RC). Next, from the same SSH session:

  1. HTTPS (required: the production session cookie is Secure, so sign-in
     only works over HTTPS). Port 443 must be open in the Azure NSG.
       sudo apt-get install -y certbot python3-certbot-nginx
       sudo certbot --nginx -d ${DOMAIN} --redirect --agree-tos -m <your-email>

  2. Smoke test:
       sudo bash -c 'set -a; . ${PASSF}; set +a; BASE_URL=https://${DOMAIN} ${APP}/deploy/smoke-test.sh'

  Operator passwords for the panel: sudo cat ${PASSF}
EOF
exit $RC
